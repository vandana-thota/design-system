// Turns tokens/tokens.json into the CSS files in src/styles/tokens/.
// Run with: npm run tokens
//
// Every value is read from `token.original` (the alias as written in the JSON), so the CSS keeps
// the chain semantic -> primitive as var() references and theme / breakpoint overrides just work.

const HEADER = '/* Generated by Style Dictionary from tokens/tokens.json. Do not edit by hand. */\n\n';

const kebab = (parts) => parts.join('-');

// CSS variable name for a token (spec: kebab case of the path).
// Primitives get a `prim-` prefix so they never become Tailwind classes.
const varName = (path) => (path[0] === 'primitive' ? `--prim-${kebab(path.slice(1))}` : `--${kebab(path.slice(1))}`);

// '{semantic.color.bg.surface}' -> 'var(--color-bg-surface)'
const toCss = (value) =>
  String(value).replace(/\{([^}]+)\}/g, (_, ref) => `var(${varName(ref.split('.'))})`);

const decl = (name, value) => `  ${name}: ${toCss(value)};\n`;
const block = (selector, body) => (body ? `${selector} {\n${body}}\n\n` : '');

const original = (token) => token.original.$value;
const darkOf = (token) => token.original.$extensions?.mode?.dark;
const layerOf = (dictionary, layer) => dictionary.allTokens.filter((t) => t.path[0] === layer);

// Composite tokens (typography, transition, elevation) become one variable per field.
const kebabKey = (key) => key.replace(/[A-Z]/g, (m) => `-${m.toLowerCase()}`);
const declTokens = (token, value = original(token)) =>
  typeof value === 'object'
    ? Object.entries(value).map(([k, v]) => decl(`${varName(token.path)}-${kebabKey(k)}`, v)).join('')
    : decl(varName(token.path), value);

const formats = {
  'css/primitives': ({ dictionary }) => {
    const prims = layerOf(dictionary, 'primitive');
    const motion = prims.filter((t) => t.path[1] === 'motion' && t.path[2] === 'duration');
    const reduced =
      '@media (prefers-reduced-motion: reduce) {\n  :root {\n' +
      motion.map((t) => `  ${decl(varName(t.path), '0ms')}`).join('') +
      '  }\n}\n';
    return HEADER + block(':root', prims.map((t) => decl(varName(t.path), original(t))).join('')) + reduced;
  },

  'css/semantic': ({ dictionary }) => {
    // Type roles live in type.css.
    const sems = layerOf(dictionary, 'semantic').filter((t) => t.path[1] !== 'type');
    const prims = layerOf(dictionary, 'primitive');
    const light = sems.map((t) => declTokens(t)).join('');
    const darkSem = sems.filter(darkOf).map((t) => decl(varName(t.path), darkOf(t))).join('');
    const darkPrim = prims.filter(darkOf).map((t) => decl(varName(t.path), darkOf(t))).join('');
    return (
      HEADER +
      block(':root,\n[data-theme="light"]', '  color-scheme: light;\n' + light) +
      block('[data-theme="dark"]', '  color-scheme: dark;\n' + darkSem + darkPrim)
    );
  },

  'css/components': ({ dictionary }) =>
    HEADER + block(':root', layerOf(dictionary, 'component').map((t) => declTokens(t)).join('')),

  'css/type': ({ dictionary }) => {
    const roles = layerOf(dictionary, 'semantic').filter((t) => t.path[1] === 'type');
    const v = (role, key) => `--type-${role}-${key}`;
    const base = roles
      .map((t) => {
        const role = t.path[2];
        return Object.entries(original(t)).map(([k, val]) => decl(v(role, kebabKey(k)), val)).join('');
      })
      .join('');
    // Only the values that change at a breakpoint are redeclared.
    const at = (mode, min) => {
      const changes = roles
        .map((t) => {
          const role = t.path[2];
          const prev = mode === 'desktop' ? { ...original(t), ...t.original.$extensions.responsive.tablet } : original(t);
          return Object.entries(t.original.$extensions.responsive[mode])
            .filter(([k, val]) => prev[k] !== val)
            .map(([k, val]) => `  ${decl(v(role, kebabKey(k)), val)}`)
            .join('');
        })
        .join('');
      return changes ? `@media (min-width: ${min}) {\n  :root {\n${changes}  }\n}\n\n` : '';
    };
    const bp = dictionary.allTokens.filter((t) => t.path[1] === 'breakpoint');
    const px = (name) => bp.find((t) => t.path[2] === name).$value;
    const utilities = roles
      .map((t) => {
        const role = t.path[2];
        return (
          `@utility text-${role} {\n` +
          `  font-family: var(${v(role, 'font-family')});\n` +
          `  font-weight: var(${v(role, 'font-weight')});\n` +
          `  font-size: var(${v(role, 'font-size')});\n` +
          `  line-height: var(${v(role, 'line-height')});\n` +
          `  letter-spacing: var(${v(role, 'letter-spacing')});\n}\n\n`
        );
      })
      .join('');
    return (
      HEADER +
      block(':root', base) +
      at('tablet', px('tablet')) +
      at('desktop', px('desktop')) +
      utilities +
      '@utility tabular {\n  font-variant-numeric: tabular-nums;\n}\n'
    );
  },

  // Short Tailwind class names for the tokens (see docs: bg-surface, text-primary, ...).
  'css/tailwind': ({ dictionary }) => {
    const all = dictionary.allTokens;
    const sem = (group) => all.filter((t) => t.path[0] === 'semantic' && t.path[1] === group);
    const lines = [];

    // bg / text / border drop their group word. Collisions with real variables are impossible
    // because the real variables keep the group word (--color-bg-surface vs --color-surface).
    const stripped = ['bg', 'text', 'border'];
    for (const t of sem('color').filter((t) => stripped.includes(t.path[2]))) {
      lines.push(`  --color-${kebab(t.path.slice(3))}: var(${varName(t.path)});`);
    }
    // accent / status already match their own variable name, so they are registered with the
    // light value here; semantic.css overrides them for dark.
    const registered = sem('color')
      .filter((t) => !stripped.includes(t.path[2]))
      .map((t) => `  ${varName(t.path)}: ${toCss(original(t))};`);

    for (const t of sem('space')) lines.push(`  --spacing-${kebab(t.path.slice(2))}: var(${varName(t.path)});`);
    // Icon sizes are exposed through the spacing namespace so `size-icon-sm` etc. exist as classes.
    for (const t of sem('size')) lines.push(`  --spacing-${kebab(t.path.slice(2))}: var(${varName(t.path)});`);
    // Radius aliases point at the primitive, since the real variable has the same name.
    for (const t of sem('radius')) lines.push(`  --radius-${kebab(t.path.slice(2))}: ${toCss(original(t))};`);
    for (const t of sem('elevation').filter((t) => t.path[2] !== 'flat')) {
      lines.push(`  --shadow-${t.path[2]}: var(--elevation-${t.path[2]}-shadow);`);
    }
    for (const f of ['display', 'sans', 'mono']) lines.push(`  --font-${f}: var(--prim-font-family-${f});`);

    const bps = all.filter((t) => t.path[1] === 'breakpoint').map((t) => `  --breakpoint-${t.path[2]}: ${t.$value};`);

    return (
      HEADER +
      '@custom-variant dark (&:where([data-theme="dark"], [data-theme="dark"] *));\n\n' +
      '/* Only the design system\'s own colors and breakpoints exist. */\n' +
      '@theme {\n  --color-*: initial;\n  --breakpoint-*: initial;\n' + bps.join('\n') + '\n' + registered.join('\n') + '\n}\n\n' +
      '@theme inline {\n' + lines.join('\n') + '\n}\n'
    );
  },
};

export default {
  source: ['tokens/tokens.json'],
  hooks: {
    formats,
    // Gives every token a unique name so Style Dictionary does not warn about collisions.
    transforms: {
      'name/path': { type: 'name', transform: (token) => token.path.join('-') },
    },
  },
  platforms: {
    css: {
      transforms: ['name/path'],
      buildPath: 'src/styles/tokens/',
      files: [
        { destination: 'primitives.css', format: 'css/primitives' },
        { destination: 'semantic.css', format: 'css/semantic' },
        { destination: 'type.css', format: 'css/type' },
        { destination: 'components.css', format: 'css/components' },
        { destination: 'tailwind.css', format: 'css/tailwind' },
      ],
    },
  },
};
